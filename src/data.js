export function detectStore(url = '') {
  const value = url.toLowerCase();
  if (value.includes('meesho.com')) return 'Meesho';
  if (value.includes('amazon.') || value.includes('amzn.to')) return 'Amazon';
  if (value.includes('flipkart.com') || value.includes('fkrt.it')) return 'Flipkart';
  if (value.includes('myntra.com') || value.includes('myntr.in')) return 'Myntra';
  if (value.includes('pinterest.') || value.includes('pin.it') || value.includes('pinimg.com')) return 'Pinterest';
  return '';
}

export function storeSearchUrl(store, query) {
  const q = encodeURIComponent(query || 'popular picks');
  if (store === 'Amazon') return `https://www.amazon.in/s?k=${q}`;
  if (store === 'Flipkart') return `https://www.flipkart.com/search?q=${q}`;
  if (store === 'Myntra') return `https://www.myntra.com/${q}`;
  if (store === 'Meesho') return `https://www.meesho.com/search?q=${q}`;
  if (store === 'Pinterest') return `https://www.pinterest.com/search/pins/?q=${q}`;
  return 'https://www.meesho.com';
}
