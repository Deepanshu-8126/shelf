function applyMeeshoPriceOverride(product) {
  if (product.store !== 'Meesho' || !product.productUrl) return product;
  let extId = '';
  try {
    const url = new URL(product.productUrl);
    extId = url.searchParams.get('ext_id') || '';
    if (!extId) {
      const segments = url.pathname.split('/').filter(Boolean);
      if (segments.length >= 3 && segments[0].toLowerCase() === 's' && segments[1].toLowerCase() === 'p') extId = segments[2];
      if (!extId && segments.length >= 2 && segments[segments.length - 2].toLowerCase() === 'p') extId = segments[segments.length - 1];
    }
  } catch { /* non-absolute sample URLs do not get a price override */ }
  const override = extId ? MEESHO_PRICE_OVERRIDES[extId.toLowerCase()] : null;
  if (!override) return product;
  return {
    ...product,
    price: override.price,
    oldPrice: override.oldPrice ?? null,
    priceCheckedAt: override.priceCheckedAt || product.priceCheckedAt,
    affiliateUrl: override.affiliateUrl || product.affiliateUrl || '',
    category: override.category || product.category,
    subtitle: override.subtitle || product.subtitle,
    priceSyncManaged: true,
  };
}

